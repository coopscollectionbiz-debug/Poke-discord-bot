"""05-missing-animations.py — read-only. Writes MISSING-ANIMATIONS.md from summary.json.
Usage: python -P -E 05-missing-animations.py summary.json MISSING-ANIMATIONS.md
"""
import collections, json, sys

S = json.load(open(sys.argv[1], encoding="utf8"))
rows = S["rows"]
sp = [r for r in rows if r["kind"] == "species"]
fm = [r for r in rows if r["kind"] != "species"]
L = []
p = L.append
p("# Missing animations — Generations 6–9\n")
p(f"Generated by `scripts/05-missing-animations.py` from the probe run of {S['probeGeneratedAt']} (UTC). "
  "\"Animated\" means a verified, decodable, multi-frame GIF in the BW 2D pixel-art style (Showdown `gen5ani`, PokéAPI "
  "`black-white/animated`, or a Smogon tracker attachment). 3D-model GIFs (Showdown `ani`, PokéAPI `other/showdown`) never count.\n")
p("Column key: **Static** is what the bot could show instead (S = Showdown `gen5`, P = PokéAPI `black-white`). "
  "**3D GIF** = a 3D-model animation exists on Showdown `ani` (rejected for style). Animator reservations for missing sprites are in `sources/smogon-trackers/` (Animator column).\n")

def tracker_note(r):
    return ""

for title, cond in (("1. Species with no animated 2D front sprite", lambda r: r["normal_animated_2d"] == "no"),):
    miss = [r for r in sp if cond(r)]
    p(f"## {title} ({len(miss)} of {len(sp)})\n")
    for g in (6, 7, 8, 9):
        rs = [r for r in miss if r["generation"] == g]
        p(f"### Gen {g} — {len(rs)} species\n")
        if not rs:
            p("None.\n"); continue
        p("| # | Pokémon | Static | Static shiny | 3D GIF | Class |")
        p("|---:|---|---|---|---|---|")
        for r in rs:
            st = {"sds": "S", "pas": "P"}.get(r["staticSrc"], "—")
            p(f"| {r['national_dex_id']} | {r['pokemon_name']} | {st} | {r['shiny_static_2d']} | {'yes' if r['ani3d'] else 'no'} | {r['classification']} |")
        p("")

p("## 2. Species with an animated front but no animated shiny\n")
rs = [r for r in sp if r["normal_animated_2d"] == "yes" and r["shiny_animated_2d"] == "no"]
p("| # | Pokémon | Gen | Front source | Static shiny available | Notes |")
p("|---:|---|---:|---|---|---|")
for r in rs:
    p(f"| {r['national_dex_id']} | {r['pokemon_name']} | {r['generation']} | {r['frontSrc']} | {r['shiny_static_2d']} | {r['missing_assets']} |")
p("")

p("## 3. Species whose animation exists only as an unpublished Smogon tracker attachment\n")
p("These GIFs decode and look correct, but they are not on Showdown or PokéAPI yet, so their QC status is unknown. Re-check before use.\n")
p("| # | Pokémon | Gen | Tracker URL |")
p("|---:|---|---:|---|")
for r in sp:
    if r["frontSrc"] == "sm":
        p(f"| {r['national_dex_id']} | {r['pokemon_name']} | {r['generation']} | {r['preferred_url']} |")
p("")

p("## 4. Species missing animated back sprites (front is animated)\n")
p("The bot shows fronts only today, so this does not block anything. Listed for completeness.\n")
for g in (6, 7, 8, 9):
    rs = [r for r in sp if r["generation"] == g and r["normal_animated_2d"] == "yes" and (r["back_animated_2d"] == "no" or r["shiny_back_animated_2d"] == "no")]
    p(f"- **Gen {g} ({len(rs)}):** " + (", ".join(f"{r['pokemon_name']} ({'no back' if r['back_animated_2d']=='no' else 'no shiny back'})" for r in rs) or "none"))
p("")

p("## 5. Alternate forms with no animated 2D front\n")
cats = collections.OrderedDict()
for r in fm:
    if r["normal_animated_2d"] == "no":
        cats.setdefault(r["category"], []).append(r)
for cat, rs in cats.items():
    p(f"- **{cat} ({len(rs)}):** " + ", ".join(f"`{r['form_identifier']}` ({r['classification']})" for r in rs))
p("")
open(sys.argv[2], "w", encoding="utf8").write("\n".join(L) + "\n")
print("wrote", sys.argv[2])
