// ==========================================================
// tools/balance-report.mjs — exact encounter probabilities before/after
// releasing generations, using the same formula as the live selector
// (tools/lib/encounterModel.mjs mirrors utils/weightedRandom.js; checked
// against the real selector by tests/gen69Balance.test.js).
//
// Run:  npm run report:balance            → docs/gen6-9/BALANCE-DATA.md
//       npm run report:balance -- --gen7  → docs/gen6-9/GEN7-ENCOUNTER-COMPARISON.md
// ==========================================================

import fs from "fs";
import { TIERS, weightedOdds, uniformOdds, slotOdds } from "./lib/encounterModel.mjs";

const DEX = Object.values(JSON.parse(fs.readFileSync(new URL("../pokemonData.json", import.meta.url), "utf8")));
const pool = (gens) => DEX.filter((p) => gens.includes(p.generation));
const CLASSIC = [1, 2, 3, 4, 5];
const pct = (x, d = 2) => `${(100 * x).toFixed(d)}%`;
const one = (x) => (x > 0 ? `1 in ${Math.round(1 / x).toLocaleString("en-US")}` : "—");
const rel = (a, b) => (b > 0 ? `${((a / b) * 100).toFixed(1)}%` : "—");
const RANKS = [["No rank (<100 TP)", null], ["Novice", "Novice Trainer"], ["Master Trainer", "Master Trainer"], ["Legend", "Legend"]];
const BALLS = ["pokeball", "greatball", "ultraball"];
const out = [];
const p = (s = "") => out.push(s);

function gen7Report() {
  const before = pool(CLASSIC), after = pool([...CLASSIC, 7]);
  const isNew = (x) => x.generation === 7;
  p("# Gen 7 (Alola) release — encounter probability before/after");
  p();
  p("Generated by `npm run report:balance -- --gen7` from `pokemonData.json` and the live weights/multipliers in `utils/weightedRandom.js`. **Exact** values (no sampling); `tests/gen69Balance.test.js` checks the formula against the real selector.");
  p();
  p("How the selector works: every species gets its tier's weight (× rank and ball multipliers). A tier's share of draws is therefore *(species in the tier × weight) ÷ total weight* — adding 88 species raises the share of tiers they join and lowers everything else, and splits each tier among more species. Quests pick uniformly; the weekly pack and starter pack use fixed tier slots.");
  p();
  p("## Pool size by tier");
  p();
  p(`| | ${TIERS.join(" | ")} | Total |`);
  p(`|---|${TIERS.map(() => "---:").join("|")}|---:|`);
  for (const [name, l] of [["Before (Gens 1–5)", before], ["After (+ Alola)", after], ["Alola added", after.filter(isNew)]]) {
    p(`| ${name} | ${TIERS.map((t) => l.filter((x) => x.tier === t).length).join(" | ")} | ${l.length} |`);
  }
  p();
  p("## Tier share per draw — Poké Ball (chat catch, /daily, /recruit, dashboard Poké Ball)");
  p();
  for (const [label, rank] of RANKS) {
    const b = weightedOdds(before, { rank, ball: "pokeball" }), a = weightedOdds(after, { rank, ball: "pokeball" });
    p(`**${label}**`);
    p();
    p(`| | ${TIERS.join(" | ")} |`);
    p(`|---|${TIERS.map(() => "---:").join("|")}|`);
    p(`| Before | ${TIERS.map((t) => pct(b.tierShare[t])).join(" | ")} |`);
    p(`| After | ${TIERS.map((t) => pct(a.tierShare[t])).join(" | ")} |`);
    p();
  }
  p("## Tier share per draw — Great Ball and Ultra Ball (dashboard)");
  p();
  for (const ball of ["greatball", "ultraball"]) {
    for (const [label, rank] of [RANKS[1], RANKS[3]]) {
      const b = weightedOdds(before, { rank, ball }), a = weightedOdds(after, { rank, ball });
      p(`**${ball === "greatball" ? "Great Ball" : "Ultra Ball"}, ${label}**`);
      p();
      p(`| | ${TIERS.join(" | ")} |`);
      p(`|---|${TIERS.map(() => "---:").join("|")}|`);
      p(`| Before | ${TIERS.map((t) => pct(b.tierShare[t])).join(" | ")} |`);
      p(`| After | ${TIERS.map((t) => pct(a.tierShare[t])).join(" | ")} |`);
      p();
    }
  }
  p("## Legendary and Mythical per draw");
  p();
  p("| Mechanism | Legendary before → after | of which existing Legendaries after | Mythic before → after | of which existing Mythics after |");
  p("|---|---|---|---|---|");
  const rows = [
    ["Poké Ball, no rank", weightedOdds(before, { rank: null }), weightedOdds(after, { rank: null })],
    ["Poké Ball, Legend", weightedOdds(before, { rank: "Legend" }), weightedOdds(after, { rank: "Legend" })],
    ["Ultra Ball, Legend", weightedOdds(before, { rank: "Legend", ball: "ultraball" }), weightedOdds(after, { rank: "Legend", ball: "ultraball" })],
    ["/quest (uniform)", uniformOdds(before), uniformOdds(after)],
  ];
  for (const [name, b, a] of rows) {
    const exL = a.perSpecies.legendary * before.filter((x) => x.tier === "legendary").length;
    const exM = a.perSpecies.mythic * before.filter((x) => x.tier === "mythic").length;
    p(`| ${name} | ${pct(b.tierShare.legendary, 3)} → ${pct(a.tierShare.legendary, 3)} | ${pct(exL, 3)} | ${pct(b.tierShare.mythic, 3)} → ${pct(a.tierShare.mythic, 3)} | ${pct(exM, 3)} |`);
  }
  p();
  p("## One specific existing Pokémon per draw (Poké Ball, no rank)");
  p();
  const b0 = weightedOdds(before, { rank: null }), a0 = weightedOdds(after, { rank: null });
  p("| Existing Pokémon (tier) | Before | After | After ÷ before |");
  p("|---|---|---|---:|");
  for (const id of [1, 25, 133, 6, 149, 144, 150, 151, 493]) {
    const s = DEX.find((x) => x.id === id);
    p(`| ${s.name} (${s.tier}) | ${one(b0.perSpecies[s.tier])} | ${one(a0.perSpecies[s.tier])} | ${rel(a0.perSpecies[s.tier], b0.perSpecies[s.tier])} |`);
  }
  p();
  p("Same ratio by tier and mechanism (any single existing species):");
  p();
  p(`| Mechanism | ${TIERS.join(" | ")} |`);
  p(`|---|${TIERS.map(() => "---:").join("|")}|`);
  for (const [name, f] of [
    ["Poké Ball, no rank", (l) => weightedOdds(l, { rank: null }).perSpecies],
    ["Poké Ball, Master Trainer", (l) => weightedOdds(l, { rank: "Master Trainer" }).perSpecies],
    ["Great Ball, Legend", (l) => weightedOdds(l, { rank: "Legend", ball: "greatball" }).perSpecies],
    ["Ultra Ball, Legend", (l) => weightedOdds(l, { rank: "Legend", ball: "ultraball" }).perSpecies],
    ["/quest (uniform)", (l) => uniformOdds(l).perSpecies],
    ["Weekly pack / starter pack slot (common–rare slots only)", (l) => Object.fromEntries(TIERS.map((t) => [t, ["common", "uncommon", "rare"].includes(t) ? slotOdds(l, t) : 0]))],
  ]) {
    const b = f(before), a = f(after);
    p(`| ${name} | ${TIERS.map((t) => rel(a[t], b[t])).join(" | ")} |`);
  }
  p();
  p("## Share of draws that are an Alola species");
  p();
  p("| Mechanism | Share |");
  p("|---|---:|");
  for (const [name, o] of [["Poké Ball, no rank", a0], ["Poké Ball, Legend", weightedOdds(after, { rank: "Legend" })], ["Ultra Ball, Legend", weightedOdds(after, { rank: "Legend", ball: "ultraball" })], ["/quest", uniformOdds(after)]]) {
    const share = TIERS.reduce((s, t) => s + o.perSpecies[t] * after.filter((x) => isNew(x) && x.tier === t).length, 0);
    p(`| ${name} | ${pct(share, 1)} |`);
  }
  const wk = ["common", "common", "common", "uncommon", "uncommon", "rare"];
  const wkShare = wk.reduce((s, t) => s + after.filter((x) => isNew(x) && x.tier === t).length / after.filter((x) => x.tier === t).length, 0) / wk.length;
  p(`| Weekly pack (avg per slot) | ${pct(wkShare, 1)} |`);
  p();
  p("## Shiny");
  p();
  p("Shiny odds per acquisition are unchanged (`shinyOdds.js`, 1/500 → 1/250 by TP). A shiny of one specific existing species becomes rarer by the same ratios as above.");
  p();
  p("## Reading the numbers");
  p();
  const leg = rows[0];
  p(`- Tier shares move modestly because Alola's 88 species skew rare/epic/legendary: e.g. Poké Ball, no rank, Legendary ${pct(leg[1].tierShare.legendary, 2)} → ${pct(leg[2].tierShare.legendary, 2)}, Common ${pct(b0.tierShare.common)} → ${pct(a0.tierShare.common)}.`);
  p(`- Each existing species becomes rarer: ${rel(a0.perSpecies.common, b0.perSpecies.common)} of today's odds for every species under the weighted selector (the total weight grows uniformly for all tiers), ${rel(uniformOdds(after).perSpecies.common, uniformOdds(before).perSpecies.common)} under quests, and per tier for pack slots (common ${rel(slotOdds(after, "common"), slotOdds(before, "common"))}, uncommon ${rel(slotOdds(after, "uncommon"), slotOdds(before, "uncommon"))}, rare ${rel(slotOdds(after, "rare"), slotOdds(before, "rare"))}).`);
  p("- No proposed balance change is applied; these are the consequences of the existing rules.");
}

function allScenarios() {
  const SCEN = [["Today (Gens 1–5)", CLASSIC], ["+ Gen 7", [...CLASSIC, 7]], ["+ Gens 6–7", [...CLASSIC, 6, 7]], ["+ Gens 6–8", [...CLASSIC, 6, 7, 8]], ["All (Gens 1–9)", [...CLASSIC, 6, 7, 8, 9]]];
  p("# Gen 6–9 balance data (generated)");
  p();
  p("Exact values from `npm run report:balance` (formula mirrors `utils/weightedRandom.js`; see tests/gen69Balance.test.js). Poké Ball, no rank, unless stated.");
  p();
  p("## Species per rarity tier");
  p();
  p(`| Scenario | ${TIERS.join(" | ")} | Total |`);
  p(`|---|${TIERS.map(() => "---:").join("|")}|---:|`);
  for (const [n, g] of SCEN) { const l = pool(g); p(`| ${n} | ${TIERS.map((t) => l.filter((x) => x.tier === t).length).join(" | ")} | ${l.length} |`); }
  p();
  p("## Tier share per draw (weighted selector)");
  p();
  p(`| Scenario | ${TIERS.join(" | ")} |`);
  p(`|---|${TIERS.map(() => "---:").join("|")}|`);
  for (const [n, g] of SCEN) { const o = weightedOdds(pool(g), { rank: null }); p(`| ${n} | ${TIERS.map((t) => pct(o.tierShare[t])).join(" | ")} |`); }
  p();
  p("## Odds of one specific existing species, relative to today");
  p();
  p("| Scenario | Weighted selector (any tier) | /quest | Weekly/starter slot: common / uncommon / rare |");
  p("|---|---:|---:|---|");
  const b = pool(CLASSIC), wb = weightedOdds(b, { rank: null }), ub = uniformOdds(b);
  for (const [n, g] of SCEN) {
    const l = pool(g), w = weightedOdds(l, { rank: null }), u = uniformOdds(l);
    p(`| ${n} | ${rel(w.perSpecies.common, wb.perSpecies.common)} | ${rel(u.perSpecies.common, ub.perSpecies.common)} | ${["common", "uncommon", "rare"].map((t) => rel(slotOdds(l, t), slotOdds(b, t))).join(" / ")} |`);
  }
  p();
  p("## Share of draws that are a Gen 6–9 species (weighted selector)");
  p();
  p("| Scenario | Share |");
  p("|---|---:|");
  for (const [n, g] of SCEN) {
    const l = pool(g), o = weightedOdds(l, { rank: null });
    p(`| ${n} | ${pct(TIERS.reduce((s, t) => s + o.perSpecies[t] * l.filter((x) => x.generation >= 6 && x.tier === t).length, 0), 1)} |`);
  }
  p();
  p("## New species by tier and generation");
  p();
  p(`| Generation | ${TIERS.join(" | ")} | Total |`);
  p(`|---|${TIERS.map(() => "---:").join("|")}|---:|`);
  for (const g of [6, 7, 8, 9]) { const l = DEX.filter((x) => x.generation === g); p(`| Gen ${g} | ${TIERS.map((t) => l.filter((x) => x.tier === t).length).join(" | ")} | ${l.length} |`); }
}

if (process.argv.includes("--gen7")) gen7Report(); else allScenarios();
console.log(out.join("\n"));
