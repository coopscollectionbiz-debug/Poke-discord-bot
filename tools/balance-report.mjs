// ==========================================================
// tools/balance-report.mjs — economy impact of releasing Gens 6–9.
// Uses the live selection code (weightedRandom.js tiers/weights) and the
// real catalogue; prints Markdown (docs/gen6-9/BALANCE-DATA.md).
// Run: npm run report:balance > docs/gen6-9/BALANCE-DATA.md
// ==========================================================

import fs from "fs";
import { POKEMON_RARITY_WEIGHTS } from "../utils/weightedRandom.js";

const DEX = Object.values(JSON.parse(fs.readFileSync(new URL("../pokemonData.json", import.meta.url), "utf8")));
const TIERS = ["common", "uncommon", "rare", "epic", "legendary", "mythic"];
const SCENARIOS = [
  ["Today (Gens 1–5)", [1, 2, 3, 4, 5]],
  ["+ Gen 7 (Alola)", [1, 2, 3, 4, 5, 7]],
  ["+ Gens 6–7", [1, 2, 3, 4, 5, 6, 7]],
  ["+ Gens 6–8", [1, 2, 3, 4, 5, 6, 7, 8]],
  ["All (Gens 1–9)", [1, 2, 3, 4, 5, 6, 7, 8, 9]],
];
const pool = (gens) => DEX.filter((p) => gens.includes(p.generation));
const count = (list, tier) => list.filter((p) => p.tier === tier).length;
const totalW = TIERS.reduce((a, t) => a + POKEMON_RARITY_WEIGHTS[t], 0);
const pct = (x) => `${(100 * x).toFixed(1)}%`;

const out = [];
const p = (s = "") => out.push(s);
p("# Gen 6–9 balance data (generated)");
p();
p("Generated by `tools/balance-report.mjs` from `pokemonData.json` and the live weights in `utils/weightedRandom.js`. Poké Ball baseline, Novice rank; Great/Ultra Balls and rank multipliers change the tier odds, but they scale every species in a tier equally, so the per-species ratios below hold for them too.");
p();
p("## Species per rarity tier");
p();
p(`| Scenario | ${TIERS.join(" | ")} | Total |`);
p(`|---|${TIERS.map(() => "---:").join("|")}|---:|`);
for (const [name, gens] of SCENARIOS) {
  const l = pool(gens);
  p(`| ${name} | ${TIERS.map((t) => count(l, t)).join(" | ")} | ${l.length} |`);
}
p();
p("## Tier odds per draw (unchanged by any release)");
p();
p(`| ${TIERS.join(" | ")} |`);
p(`|${TIERS.map(() => "---:").join("|")}|`);
p(`| ${TIERS.map((t) => pct(POKEMON_RARITY_WEIGHTS[t] / totalW)).join(" | ")} |`);
p();
p("## Chance that a draw is one specific existing (Gen 1–5) species, relative to today");
p();
p(`| Scenario | ${TIERS.join(" | ")} |`);
p(`|---|${TIERS.map(() => "---:").join("|")}|`);
const base = pool([1, 2, 3, 4, 5]);
for (const [name, gens] of SCENARIOS) {
  const l = pool(gens);
  p(`| ${name} | ${TIERS.map((t) => `${((count(base, t) / count(l, t)) * 100).toFixed(0)}%`).join(" | ")} |`);
}
p();
p("## Share of draws that are a Gen 6–9 species");
p();
p("| Scenario | Share of draws |");
p("|---|---:|");
for (const [name, gens] of SCENARIOS) {
  const l = pool(gens);
  const share = TIERS.reduce((a, t) => a + (POKEMON_RARITY_WEIGHTS[t] / totalW) * (count(l.filter((x) => x.generation >= 6), t) / (count(l, t) || 1)), 0);
  p(`| ${name} | ${pct(share)} |`);
}
p();
p("## New species by tier and generation");
p();
p(`| Generation | ${TIERS.join(" | ")} | Total |`);
p(`|---|${TIERS.map(() => "---:").join("|")}|---:|`);
for (const g of [6, 7, 8, 9]) {
  const l = DEX.filter((x) => x.generation === g);
  p(`| Gen ${g} | ${TIERS.map((t) => count(l, t)).join(" | ")} | ${l.length} |`);
}
console.log(out.join("\n"));
