// ==========================================================
// tools/generate-move-flags.mjs — move flags for battle abilities (Mega M2).
//
// battleData.json is left untouched (ordinary battles must not change); the
// flags live in data/battle/move-flags.json and are read only by the ability
// framework (utils/battle/abilities.js):
//   contact, punch, bite, pulse, slicing, bullet  (Showdown move flags)
//   secondary  (the move has a secondary effect: Sheer Force)
// Only moves present in battleData.json are listed, and only true flags.
//
// Run: npm run generate:move-flags     (needs the @pkmn/dex dev dependency)
// ==========================================================

import fs from "fs";
import { Dex } from "@pkmn/dex";

const ROOT = new URL("..", import.meta.url);
const battle = JSON.parse(fs.readFileSync(new URL("battleData.json", ROOT), "utf8"));
const FLAGS = ["contact", "punch", "bite", "pulse", "slicing", "bullet"];
const out = {};
const missing = [];
for (const id of Object.keys(battle.moves).sort()) {
  const m = Dex.moves.get(id);
  if (!m?.exists) { missing.push(id); continue; }
  const f = {};
  for (const k of FLAGS) if (m.flags?.[k]) f[k] = true;
  if (m.secondary || (Array.isArray(m.secondaries) && m.secondaries.length)) f.secondary = true;
  if (Object.keys(f).length) out[id] = f;
}
if (missing.length) { console.error(`moves unknown to @pkmn/dex: ${missing.join(", ")}`); process.exit(1); }
fs.mkdirSync(new URL("data/battle/", ROOT), { recursive: true });
fs.writeFileSync(new URL("data/battle/move-flags.json", ROOT), JSON.stringify({
  note: "Move flags for battle abilities (generated by tools/generate-move-flags.mjs from @pkmn/dex 0.10.12; do not edit). battleData.json is unchanged.",
  moves: out,
}, null, 1) + "\n");
const count = (k) => Object.values(out).filter((f) => f[k]).length;
console.log(`moves ${Object.keys(battle.moves).length}, flagged ${Object.keys(out).length}:`, Object.fromEntries([...FLAGS, "secondary"].map((k) => [k, count(k)])));
